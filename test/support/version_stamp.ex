defmodule Crosswake.TestSupport.VersionStamp do
  @moduledoc """
  Normalizes the crosswake version inside generated output so fixture
  comparisons survive a release version bump.

  Only the version carried by a `Generated by crosswake X.Y.Z` stamp, or by a
  JSON `"crosswake_version": "X.Y.Z"` value, is ignored. The `template_version`
  suffix, every other byte, and a missing stamp all still differ.
  """

  @token "<CROSSWAKE_VERSION>"
  @semver "[0-9]+\\.[0-9]+\\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\\+[0-9A-Za-z.-]+)?"

  @stamp Regex.compile!("(Generated by crosswake )" <> @semver)
  @json Regex.compile!("(\"crosswake_version\"\\s*:\\s*\")" <> @semver <> "(\")")

  @spec normalize_stamp(binary()) :: binary()
  def normalize_stamp(bytes) when is_binary(bytes) do
    Regex.replace(@stamp, bytes, "\\1" <> @token)
  end

  @spec stamp_count(binary()) :: non_neg_integer()
  def stamp_count(bytes) when is_binary(bytes), do: length(Regex.scan(@stamp, bytes))

  @spec normalize_crosswake_version(binary()) :: binary()
  def normalize_crosswake_version(bytes) when is_binary(bytes) do
    Regex.replace(@json, bytes, "\\1" <> @token <> "\\2")
  end

  @spec crosswake_version_count(binary()) :: non_neg_integer()
  def crosswake_version_count(bytes) when is_binary(bytes),
    do: length(Regex.scan(@json, bytes))
end
