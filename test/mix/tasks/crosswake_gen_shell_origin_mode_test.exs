defmodule Mix.Tasks.Crosswake.Gen.ShellOriginModeTest do
  use ExUnit.Case, async: false

  alias Crosswake.TestSupport.VersionStamp

  @golden Path.expand("../../fixtures/shell/ios/Info.plist.production.golden", __DIR__)
  @manifest Path.expand("../../fixtures/shell/ios/production_generation.sha256.json", __DIR__)
  @info_plist "native/ios/crosswake_shell/CrosswakeShell/Info.plist"
  @activation "native/ios/crosswake_shell/Fixtures/route_activation.json"

  @local_block """
      <key>NSAppTransportSecurity</key>
      <dict>
          <key>NSAllowsLocalNetworking</key>
          <true/>
      </dict>
      <key>CrosswakeOriginMode</key>
      <string>local_loopback</string>
  """

  setup do
    previous = Application.get_env(:crosswake, :ios_host)

    target =
      Path.join(System.tmp_dir!(), "gen-shell-origin-#{System.unique_integer([:positive])}")

    File.mkdir_p!(target)

    on_exit(fn ->
      if previous,
        do: Application.put_env(:crosswake, :ios_host, previous),
        else: Application.delete_env(:crosswake, :ios_host)

      Mix.Task.reenable("crosswake.gen.shell")
      File.rm_rf!(target)
    end)

    {:ok, target: target}
  end

  defp declaration(extra \\ []) do
    [
      router: Crosswake.TestSupport.RouterFixtures.ManagedRouter,
      origin: "https://study.crosswake.test",
      entry_route_id: "study-session",
      app_bundle_id: "dev.crosswake.hostapp",
      proof_app_bundle_id: "dev.crosswake.hostapp.proof",
      device_signing: [mode: :automatic, team_id: "ABCDE12345"]
    ]
    |> Keyword.merge(extra)
  end

  defp generate(target, declaration) do
    Application.put_env(:crosswake, :ios_host, declaration)
    Mix.Task.reenable("crosswake.gen.shell")

    ExUnit.CaptureIO.capture_io(fn ->
      Mix.Tasks.Crosswake.Gen.Shell.run(["ios", "--target", target])
    end)
  end

  # Compares generated bytes to the committed golden, ignoring only the crosswake
  # version inside the generated-by stamp. The golden must still carry that stamp.
  defp assert_matches_golden(actual) do
    golden = File.read!(@golden)
    assert VersionStamp.stamp_count(golden) == 1
    assert VersionStamp.normalize_stamp(actual) == VersionStamp.normalize_stamp(golden)
  end

  defp normalized_digests(target, rules) do
    target
    |> Path.join("**/*")
    |> Path.wildcard(match_dot: true)
    |> Enum.filter(&File.regular?/1)
    |> Map.new(fn path ->
      relative = Path.relative_to(path, target)

      bytes =
        Enum.reduce(rules, File.read!(path), fn
          %{"path" => ^relative, "pattern" => pattern, "token" => token}, acc ->
            Regex.replace(Regex.compile!(pattern), acc, token)

          _rule, acc ->
            acc
        end)

      {relative, :crypto.hash(:sha256, bytes) |> Base.encode16(case: :lower)}
    end)
  end

  test "production generation without origin_mode equals the base golden and manifest", %{
    target: target
  } do
    generate(target, declaration())

    assert_matches_golden(File.read!(Path.join(target, @info_plist)))

    manifest = @manifest |> File.read!() |> Jason.decode!()
    expected = manifest["files"]
    actual = normalized_digests(target, manifest["normalization"])

    assert Enum.sort(Map.keys(actual)) == Enum.sort(Map.keys(expected)),
           "generated file set changed: " <>
             inspect(%{
               added: Map.keys(actual) -- Map.keys(expected),
               missing: Map.keys(expected) -- Map.keys(actual)
             })

    assert map_size(expected) > 0

    for {relative, digest} <- expected do
      assert actual[relative] == digest, "generated bytes changed for #{relative}"
    end
  end

  test "local_loopback declaration emits the Info.plist block and an http activation origin", %{
    target: target
  } do
    generate(target, declaration(origin: "http://127.0.0.1:4790", origin_mode: :local_loopback))

    plist = File.read!(Path.join(target, @info_plist))
    anchor = "    <key>LSRequiresIPhoneOS</key>\n    <true/>\n"

    assert length(String.split(plist, @local_block)) == 2

    assert String.contains?(
             plist,
             anchor <> @local_block <> "    <key>UIApplicationSceneManifest</key>"
           )

    activation = target |> Path.join(@activation) |> File.read!() |> Jason.decode!()
    assert activation["origin"] == "http://127.0.0.1:4790"
  end

  @local_declaration [origin: "http://127.0.0.1:4790", origin_mode: :local_loopback]

  test "prod -> local -> prod round trip on one target restores the production golden", %{
    target: target
  } do
    plist_path = Path.join(target, @info_plist)

    generate(target, declaration())
    assert_matches_golden(File.read!(plist_path))

    generate(target, declaration(@local_declaration))
    local = File.read!(plist_path)
    assert length(String.split(local, @local_block)) == 2
    assert local =~ "NSAllowsLocalNetworking"

    activation = target |> Path.join(@activation) |> File.read!() |> Jason.decode!()
    assert activation["origin"] == "http://127.0.0.1:4790"

    generate(target, declaration())
    assert_matches_golden(File.read!(plist_path))
    refute File.read!(plist_path) =~ "NSAppTransportSecurity"
    refute File.read!(plist_path) =~ "CrosswakeOriginMode"

    # local -> prod -> local leaves exactly one block
    generate(target, declaration(@local_declaration))
    assert length(String.split(File.read!(plist_path), @local_block)) == 2
  end

  test "legacy path without :ios_host strips exactly the Crosswake block", %{target: target} do
    plist_path = Path.join(target, @info_plist)

    generate(target, declaration(@local_declaration))
    local = File.read!(plist_path)

    Application.delete_env(:crosswake, :ios_host)
    Mix.Task.reenable("crosswake.gen.shell")

    ExUnit.CaptureIO.capture_io(fn ->
      Mix.Tasks.Crosswake.Gen.Shell.run(["ios", "--target", target])
    end)

    final = File.read!(plist_path)
    refute final =~ "NSAppTransportSecurity"
    refute final =~ "CrosswakeOriginMode"

    assert final ==
             String.replace(local, Crosswake.Shell.IOSHostOriginMode.block(:local_loopback), "")

    assert_matches_golden(final)
  end

  @anchor "    <key>LSRequiresIPhoneOS</key>\n    <true/>"
  @d13 "origin mode: local loopback (http://127.0.0.1:4790); Simulator only; not production-ready; before distributing, switch to your HTTPS production origin and regenerate"
  @drift "cause: origin mode changed; repair: rerun mix crosswake.gen.shell ios"

  defp run_task(target, flags) do
    Mix.Task.reenable("crosswake.gen.shell")

    ExUnit.CaptureIO.capture_io(fn ->
      send(self(), {:result, try_run(["ios" | flags] ++ ["--target", target])})
    end)
    |> then(fn out ->
      receive do
        {:result, result} -> {out, result}
      end
    end)
  end

  defp try_run(args) do
    Mix.Tasks.Crosswake.Gen.Shell.run(args)
    :ok
  rescue
    e in Mix.Error -> {:raised, Exception.message(e)}
  end

  defp plist(target), do: Path.join(target, @info_plist)

  defp host_ats_plist(production_bytes),
    do:
      String.replace(
        production_bytes,
        @anchor,
        @anchor <>
          "\n    <key>NSAppTransportSecurity</key>\n    <dict>\n        <key>NSAllowsLocalNetworking</key>\n        <true/>\n        <key>NSExceptionDomains</key>\n        <dict/>\n    </dict>"
      )

  test "a host-edited local plist is refused and left unchanged", %{target: target} do
    generate(target, declaration(@local_declaration))

    edited =
      String.replace(
        File.read!(plist(target)),
        "<true/>\n    </dict>",
        "<true/>\n        <key>Other</key>\n        <true/>\n    </dict>"
      )

    File.write!(plist(target), edited)

    {_out, result} = run_task(target, [])
    assert {:raised, message} = result
    assert message =~ "info_plist_conflict"
    assert File.read!(plist(target)) == edited
  end

  test "production host with its own ATS dict is untouched and --check is current", %{
    target: target
  } do
    generate(target, declaration())
    hosted = host_ats_plist(File.read!(plist(target)))
    File.write!(plist(target), hosted)

    {_out, result} = run_task(target, [])
    assert result == :ok
    assert File.read!(plist(target)) == hosted

    {out, result} = run_task(target, ["--check"])
    assert result == :ok
    assert out =~ "checked managed iOS outputs: current"
    refute out =~ "origin mode:"

    # same plist, declaration switched to local: refused, unchanged
    Application.put_env(:crosswake, :ios_host, declaration(@local_declaration))
    {_out, result} = run_task(target, [])
    assert {:raised, message} = result
    assert message =~ "info_plist_conflict"
    assert File.read!(plist(target)) == hosted
  end

  test "--check right after local generation is current with exactly one D-13 line", %{
    target: target
  } do
    generate(target, declaration(@local_declaration))
    {out, result} = run_task(target, ["--check"])
    assert result == :ok
    assert out =~ "checked managed iOS outputs: current"
    assert length(String.split(out, @d13)) == 2
    assert length(Regex.scan(~r/^origin mode:/m, out)) == 1
  end

  test "--check right after HTTPS generation prints no origin mode line", %{target: target} do
    generate(target, declaration())
    {out, result} = run_task(target, ["--check"])
    assert result == :ok
    assert out =~ "current"
    refute out =~ ~r/^origin mode:/m
  end

  test "declaration toggled without regenerating is blocked in both directions", %{target: target} do
    generate(target, declaration())
    Application.put_env(:crosswake, :ios_host, declaration(@local_declaration))
    {out, result} = run_task(target, ["--check"])
    assert out =~ "blocked; " <> @drift
    assert {:raised, _} = result

    generate(target, declaration(@local_declaration))
    Application.put_env(:crosswake, :ios_host, declaration())
    {out, result} = run_task(target, ["--check"])
    assert out =~ "blocked; " <> @drift
    assert {:raised, _} = result
  end

  test "declared local with missing or unreadable plist is drift", %{target: target} do
    generate(target, declaration(@local_declaration))
    original = File.read!(plist(target))

    File.rm!(plist(target))
    {out, result} = run_task(target, ["--check"])
    assert out =~ "blocked; " <> @drift
    assert {:raised, _} = result

    File.write!(plist(target), original)
    File.chmod!(plist(target), 0o000)
    {out, result} = run_task(target, ["--check"])
    File.chmod!(plist(target), 0o644)
    assert out =~ "blocked; " <> @drift
    assert {:raised, _} = result
  end

  test "--diff reports needs-attention for a toggle without raising", %{target: target} do
    generate(target, declaration())
    Application.put_env(:crosswake, :ios_host, declaration(@local_declaration))
    {out, result} = run_task(target, ["--diff"])
    assert out =~ "needs-attention; " <> @drift
    assert result == :ok
  end

  test "README banner appears once for fresh local generation and never for production", %{
    target: target
  } do
    banner = Crosswake.Shell.IOSHostOriginMode.readme_banner()
    readme = Path.join(target, "native/ios/crosswake_shell/README.md")

    generate(target, declaration(@local_declaration))
    assert length(String.split(File.read!(readme), banner)) == 2

    prod =
      Path.join(System.tmp_dir!(), "gen-shell-origin-prod-#{System.unique_integer([:positive])}")

    File.mkdir_p!(prod)
    on_exit(fn -> File.rm_rf!(prod) end)
    generate(prod, declaration())
    refute File.read!(Path.join(prod, "native/ios/crosswake_shell/README.md")) =~ banner
    refute File.read!(Path.join(prod, "native/ios/crosswake_shell/README.md")) =~ "Local loopback"
  end

  test "generated Info.plist has no forbidden ATS keys and keeps WKAppBoundDomains", %{
    target: target
  } do
    for decl <- [declaration(), declaration(@local_declaration)] do
      File.rm_rf!(Path.join(target, "native"))
      generate(target, decl)
      bytes = File.read!(plist(target))

      keys = Crosswake.Shell.IOSHostOriginMode.forbidden_ats_keys()
      assert [_ | _] = keys

      for key <- keys, do: refute(bytes =~ key)

      assert bytes =~
               "<key>WKAppBoundDomains</key>\n    <array>\n        <string>example.com</string>\n    </array>"
    end
  end
end
