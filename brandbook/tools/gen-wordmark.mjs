#!/usr/bin/env node
/**
 * brandbook/tools/gen-wordmark.mjs
 * Generate a path-only "Crosswake" wordmark SVG from Space Grotesk SemiBold.
 *
 * Provenance: SpaceGrotesk[wght].ttf wght=600, pinned commit 877f891 (2026-06-11)
 * Output: brandbook/logo/tournament/candidates/wordmark-base.svg
 *
 * Key workarounds for opentype.js 2.0.0:
 *   0. Use opentype.parse(buffer.buffer) — opentype.load() is deprecated and returns undefined
 *   1. font.variation.set({wght: 600}) MUST precede any getPaths() call
 *   2. toPathData({flipY: false}) — avoids double-flip bug (issue #724, PR #850)
 *   3. baseline = font.ascender * (fontSize / font.unitsPerEm) — NOT 0
 *   4. fill-rule="evenodd" on wrapper <g> for hollow counters in o/e/a/s/C
 *
 * Usage:
 *   node brandbook/tools/gen-wordmark.mjs
 *
 * Exports:
 *   generateWordmark(ttfPath, options?) -> Promise<string|{svg,baseline}>
 */
import opentype from 'opentype.js';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '../..');

const DEFAULT_FONT_PATH = resolve(__dirname, 'fonts/SpaceGrotesk[wght].ttf');
const DEFAULT_OUT_PATH  = resolve(ROOT, 'brandbook/logo/tournament/candidates/wordmark-base.svg');

const TEXT      = 'Crosswake';
const FONT_SIZE = 72;
const WEIGHT    = 600;  // SemiBold

/**
 * Generate the wordmark SVG string.
 *
 * @param {string} ttfPath - Path to SpaceGrotesk[wght].ttf
 * @param {object} [options]
 * @param {boolean} [options.inspectBaseline=false] - If true, return {svg, baseline} instead of string
 * @returns {Promise<string|{svg:string, baseline:number}>}
 */
export async function generateWordmark(ttfPath, options = {}) {
  const { inspectBaseline = false } = options;

  // opentype.load() is deprecated in 2.0.0 and returns undefined — use parse(buffer.buffer)
  // The .buffer property converts Node Buffer to underlying ArrayBuffer as required by opentype.parse
  const ttfBuffer = readFileSync(ttfPath);
  const font = opentype.parse(ttfBuffer.buffer);

  // MUST precede getPaths: set SemiBold weight on the variable font VariationManager
  // default is wght=400 (Regular); without this the wordmark is too light
  font.variation.set({ wght: WEIGHT });

  // Correct baseline for bottom-up coordinate system:
  // font.ascender is in unitsPerEm space — scale to fontSize
  // Using 0 would render all glyphs below origin (invisible or clipped)
  const baseline = font.ascender * (FONT_SIZE / font.unitsPerEm);

  // getPaths (plural) returns one Path object per glyph — required for per-glyph id attributes
  // Using getPath (singular) would merge all glyphs, making w/k edits impossible (D-09)
  const paths  = font.getPaths(TEXT, 0, baseline, FONT_SIZE, { kerning: true });
  const glyphs = font.stringToGlyphs(TEXT);

  // Bounding box from the merged path (getPath singular) for viewBox computation
  const mergedPath = font.getPath(TEXT, 0, baseline, FONT_SIZE, { kerning: true });
  const bbox = mergedPath.getBoundingBox();

  const pathEls = paths.map((path, i) => {
    const char      = TEXT[i];
    const glyphName = glyphs[i].name || char;
    // flipY: false — getPath already applies y-negation (-cmd.y * yScale) in glyph.mjs
    // The default flipY: true in toPathData() would double-flip → vertically mirrored wordmark
    const d = path.toPathData({ flipY: false, decimalPlaces: 2 });
    return [
      `  <!-- glyph: ${glyphName}  char: ${char}  pos: ${i} -->`,
      `  <path id="glyph-${i}-${char}" d="${d}" />`
    ].join('\n');
  }).join('\n');

  const vbX = bbox.x1.toFixed(2);
  const vbW = (bbox.x2 - bbox.x1).toFixed(2);
  const vbH = FONT_SIZE.toFixed(2);

  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by brandbook/tools/gen-wordmark.mjs — hand-edit glyph-5-w and glyph-7-k for w/k cuts -->
<!-- Provenance: SpaceGrotesk[wght].ttf wght=600 at ${FONT_SIZE}px, pinned commit 877f891 -->
<!-- D-09: surgical node edits only on glyph-5-w (w apex) and glyph-7-k (k arm/leg) -->
<!-- D-04: path-only SVG (no text/rect/font elements) -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vbX} 0 ${vbW} ${vbH}">
  <g id="wordmark-base" fill="currentColor" fill-rule="evenodd">
${pathEls}
  </g>
</svg>`;

  if (inspectBaseline) {
    return { svg, baseline };
  }
  return svg;
}

// Print glyph index/name table for inspection and hand-edit planning
function printGlyphTable(text) {
  console.log('\nGlyph index/name table for "Crosswake":');
  for (let i = 0; i < text.length; i++) {
    const note = (i === 5) ? '  <-- glyph-5-w: NEEDS w apex cut (D-06)' :
                 (i === 7) ? '  <-- glyph-7-k: NEEDS k arm/leg cut (D-06)' : '';
    console.log(`  [${i}] char="${text[i]}"  id="glyph-${i}-${text[i]}"${note}`);
  }
  console.log('\nReminder: hand-edit glyph-5-w and glyph-7-k in wordmark-base.svg');
  console.log('  w: replace apex nodes with 20-deg cut (dx_per_unit_y = 2.747)');
  console.log('  k: replace arm/leg vertex with angular notch at same 20-deg slope');
  console.log('  Then save as wordmark-custom.svg as a SEPARATE commit (D-09 provenance)\n');
}

// Main: run if executed directly (not imported as a module)
const IS_MAIN = process.argv[1] === fileURLToPath(import.meta.url);

if (IS_MAIN) {
  if (!existsSync(DEFAULT_FONT_PATH)) {
    console.error(`ERROR: Font not found at ${DEFAULT_FONT_PATH}`);
    console.error('Run: bash brandbook/tools/fetch-fonts.sh');
    process.exit(1);
  }

  printGlyphTable(TEXT);

  console.log(`Generating wordmark-base.svg (wght=${WEIGHT}, fontSize=${FONT_SIZE})...`);
  const svg = await generateWordmark(DEFAULT_FONT_PATH);
  writeFileSync(DEFAULT_OUT_PATH, svg, 'utf8');
  console.log(`Written: ${DEFAULT_OUT_PATH}`);
  console.log('Path count:', (svg.match(/<path\s/g) || []).length, '(expected: 9)');
}
