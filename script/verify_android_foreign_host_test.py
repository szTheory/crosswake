def hex_package(versions):
    """The live package endpoint's releases[] objects carry only these four keys."""
    return json.dumps({'releases': [
        {'has_docs': True, 'inserted_at': '2026-01-01T00:00:00.000000Z',
         'url': f'{HEX_API}/releases/{v}', 'version': v} for v in versions]})


def maven_metadata(versions):
    entries = ''.join(f'      <version>{v}</version>\n' for v in versions)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<metadata>\n'
            f'  <groupId>{GROUP}</groupId>\n  <artifactId>{ARTIFACT}</artifactId>\n'
            '  <versioning>\n    <latest>0.2.11</latest>\n    <release>0.2.11</release>\n'
            f'    <versions>\n{entries}    </versions>\n  </versioning>\n</metadata>\n')


class Run:
    def __init__(self, result, builds, evidence, root, unmapped, gradle_env, home):
        self.result = result
        self.rc = result.returncode
        self.out = result.stdout.splitlines()
        self.builds = builds
        self.evidence = evidence
        self.root = root
        self.unmapped = unmapped
        self.gradle_env = gradle_env
        self.home = home


class ForeignHostTest(unittest.TestCase):
    def exercise(self, maven='ok', maven_versions=None, hex_versions=None, curl_fail=(),
                 generator='ok', build='ok', control='could_not_find', negctl_status=404,
                 aar_sha=None, core_build=CORE_BUILD_LINE, android_home=True, extra_args=(),
                 selftest=True, overrides=None, github_sha=RAN_ON):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder).resolve()
            bin_dir = root / 'bin'
            bin_dir.mkdir()
            (root / 'tmp').mkdir()
            home = root / 'home_real'
            home.mkdir()
            (bin_dir / 'curl').write_text(FAKE_CURL.format(python=sys.executable))
            (bin_dir / 'java').write_text(FAKE_JAVA)
            (root / 'generator.sh').write_text(FAKE_GENERATOR)
            for tool in (bin_dir / 'curl', bin_dir / 'java'):
                tool.chmod(0o755)

            aar_bytes = b'fake-aar-bytes-for-selftest'
            (root / 'aar_bytes').write_bytes(aar_bytes)
            good_digest = hashlib.sha256(aar_bytes).hexdigest()
            (root / 'aar.sha256').write_text((aar_sha or good_digest) + '\n')
            (root / 'maven.xml').write_text(
                maven_metadata(maven_versions if maven_versions is not None else DEFAULT_MAVEN_VERSIONS))
            (root / 'hex.json').write_text(
                hex_package(hex_versions if hex_versions is not None else DEFAULT_HEX_VERSIONS))
            (root / 'negctl.pom').write_text('<project/>\n')
            (root / 'generator_mode').write_text(generator)
            (root / 'build_mode').write_text(build)
            (root / 'control_mode').write_text(control)
            core_file = root / 'core.build.gradle.kts'
            core_file.write_text('plugins {}\n' + core_build)

            def entry(match, status, fixture=None, transport_fail=False):
                return {'match': match, 'status': status, 'fixture': fixture,
                        'transport_fail': transport_fail}

            maven_entry = {
                'ok': entry('maven-metadata.xml', 200, 'maven.xml'),
                'missing': entry('maven-metadata.xml', 404),
            }[maven]
            entries = [
                entry('negctl', negctl_status, 'negctl.pom' if negctl_status == 200 else None),
                maven_entry,
                entry('.aar.sha256', 200, 'aar.sha256'),
                entry('hex.example.test', 200, 'hex.json'),
            ]
            for needle in curl_fail:
                entries.insert(0, entry(needle, 0, transport_fail=True))
            (root / 'curl_map.json').write_text(json.dumps(entries))

            env = {
                'PATH': f'{bin_dir}:{os.environ.get("PATH", "/usr/bin:/bin")}',
                'HOME': str(home),
                'TMPDIR': str(root / 'tmp'),
                'FIXTURE_ROOT': str(root),
                'GITHUB_TOKEN': 'selftest-secret-token',
                'ORG_GRADLE_PROJECT_secret': 'selftest-secret',
                'FOREIGN_HOST_MAVEN_BASE': MAVEN_BASE,
                'FOREIGN_HOST_HEX_API': HEX_API,
                'FOREIGN_HOST_GENERATOR': str(root / 'generator.sh'),
                'FOREIGN_HOST_CORE_BUILD_FILE': str(core_file),
            }
            if selftest:
                env['FOREIGN_HOST_SELFTEST'] = '1'
            if github_sha:
                env['GITHUB_SHA'] = github_sha
            if android_home:
                env['ANDROID_HOME'] = str(root / 'sdk')
            if overrides is not None:
                env = {k: v for k, v in env.items() if not k.startswith('FOREIGN_HOST_')}
                env.update(overrides)
            evidence_path = root / 'out' / 'evidence.json'
            result = subprocess.run(
                ['bash', str(SCRIPT), '--evidence', str(evidence_path), '--head-sha', HEAD, *extra_args],
                env=env, capture_output=True, text=True, cwd=str(root))
            builds_file = root / 'builds'
            builds = builds_file.read_text().splitlines() if builds_file.exists() else None
            evidence = json.loads(evidence_path.read_text()) if evidence_path.exists() else None
            unmapped = (root / 'unmapped').read_text().splitlines() if (root / 'unmapped').exists() else []
            gradle_env_file = root / 'gradle_env'
            gradle_env = gradle_env_file.read_text() if gradle_env_file.exists() else ''
            leftovers = [p.name for p in (root / 'tmp').iterdir()]
            run = Run(result, builds, evidence, root, unmapped, gradle_env, str(home))
            run.leftovers = leftovers
            return run

    def assert_positive(self):
        run = self.exercise()
        self.assertEqual(run.rc, 0, run.result.stdout + run.result.stderr)
        self.assertIn('foreign-host: result PASS legs resolve,generate,settings,coordinate,build,aar,control '
                      'version 0.2.11', run.out)
        return run

    def assert_fail(self, run, leg, reason):
        self.assertEqual(run.rc, 1, run.result.stdout + run.result.stderr)
        self.assertIn(f'foreign-host: FAIL {leg} {reason}', run.out)
        self.assertTrue(run.out[-1].startswith('foreign-host: result FAIL'), run.out[-1])
        self.assertEqual(run.unmapped, [])
        self.assertIsNotNone(run.evidence)
        self.assertEqual(run.evidence['result'], 'FAIL')
        self.assertEqual(run.evidence['reason'], reason)

    # 1
    def test_positive_fixture_passes_all_seven_legs(self):
        run = self.assert_positive()
        self.assertEqual(run.unmapped, [])
        for leg in ('resolve', 'generate', 'settings', 'coordinate', 'build', 'aar', 'control'):
            self.assertTrue(any(line.startswith(f'foreign-host: leg {leg} PASS 0.2.11 ') for line in run.out), leg)
        self.assertIn('foreign-host: leg resolve PASS 0.2.11 published 0.2.11, not head version', run.out)
        self.assertEqual(run.builds, ['--no-daemon --refresh-dependencies :app:testDebugUnitTest',
                                      '--no-daemon :app:testDebugUnitTest --dry-run',
                                      '--no-daemon :app:testDebugUnitTest'])
        evidence = run.evidence
        self.assertEqual(sorted(evidence), sorted(
            ['schema', 'target_version', 'head_sha', 'ran_on', 'tests', 'control_reason',
             'script_blob', 'result', 'generator', 'reason']))
        self.assertEqual(evidence['schema'], 1)
        self.assertEqual(evidence['target_version'], '0.2.11')
        self.assertEqual(evidence['head_sha'], HEAD)
        self.assertEqual(evidence['ran_on'], RAN_ON)
        self.assertEqual(evidence['tests'], 2)
        self.assertEqual(evidence['control_reason'], 'could_not_find')
        self.assertEqual(evidence['result'], 'PASS')
        self.assertEqual(evidence['generator'], 'published')
        self.assertRegex(evidence['script_blob'], r'^[0-9a-f]{40}$')
        # Nothing sensitive reaches the Gradle environment or the evidence.
        self.assertNotIn('GITHUB_TOKEN', run.gradle_env)
        self.assertNotIn('ORG_GRADLE_PROJECT', run.gradle_env)
        self.assertNotIn(f'HOME={run.home}\n', run.gradle_env)
        self.assertNotIn('selftest-secret', json.dumps(evidence))
        self.assertEqual(run.leftovers, [], 'the work directory must be removed')

