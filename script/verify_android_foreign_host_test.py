#!/usr/bin/env python3
"""Hermetic selftest of script/verify_android_foreign_host.sh.

No network, no mix, no Java, no Gradle and no real HOME: curl, java, the generator and gradlew
are fakes in a temp directory. Every failure reason of the script has a fixture here next to a
passing positive case. The control's Gradle wording is the verbatim Gradle 8.7 output measured
in 198-RESEARCH correction C3.
"""
