FAKE_CURL = '''#!{python}
import json, os, shutil, sys
args = sys.argv[1:]
dest = None
fmt = None
i = 0
while i < len(args):
    if args[i] == '-o':
        dest = args[i + 1]
        i += 2
    elif args[i] == '-w':
        fmt = args[i + 1]
        i += 2
    elif args[i] in ('--max-time', '--retry', '--proto', '--proto-redir'):
        i += 2
    else:
        i += 1
url = args[-1]
root = os.environ['FIXTURE_ROOT']
with open(os.path.join(root, 'curl_map.json')) as handle:
    entries = json.load(handle)
for entry in entries:
    if entry['match'] in url:
        if entry.get('transport_fail'):
            sys.exit(6)
        if dest and entry.get('fixture'):
            shutil.copyfile(os.path.join(root, entry['fixture']), dest)
        elif dest:
            open(dest, 'w').close()
        if fmt:
            sys.stdout.write(str(entry['status']))
        sys.exit(0)
with open(os.path.join(root, 'unmapped'), 'a') as handle:
    handle.write(url + '\\n')
sys.exit(99)
'''

